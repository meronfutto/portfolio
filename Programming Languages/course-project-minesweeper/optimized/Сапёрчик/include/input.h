#pragma once
#include <glew.h>      // OpenGL-типы и функции
#include <glfw3.h>    // GLFW: окно, ввод, callbacks

// =====================================================
//                Input system (input.h)
// =====================================================

// -----------------------------------------------------
// Инициализация системы ввода
// -----------------------------------------------------

// Регистрирует все callback-функции GLFW:
//  - клавиатура
//  - ввод символов
//  - прокрутка колёсика
//  - кнопки мыши
// Вызывается один раз после создания окна.
void input_init(GLFWwindow* window);

// -----------------------------------------------------
// Клавиатура
// -----------------------------------------------------

// Callback на нажатие / отпускание клавиш.
// Используется для:
//  - управления игрой
//  - переключения экранов
//  - обработки TAB, ESC, Enter и т.д.
void key_callback(
    GLFWwindow* window,
    int key,
    int scancode,
    int action,
    int mods
);

// Callback на ввод символов (текст).
// Ловит именно символы, а не клавиши.
// Используется для:
//  - ввода ширины/высоты поля
//  - работы с цифрами и backspace
void char_callback(
    GLFWwindow* window,
    unsigned int codepoint
);

// -----------------------------------------------------
// Мышь
// -----------------------------------------------------

// Callback колёсика мыши.
// Используется для зума игрового поля.
void scroll_callback(
    GLFWwindow* window,
    double xoffset,
    double yoffset
);

// Callback кнопок мыши (нажали / отпустили).
// Используется для:
//  - кликов по кнопкам интерфейса
//  - кликов по игровому полю
//  - зажатия средней кнопки для перемещения камеры
void mouse_button_callback(
    GLFWwindow* window,
    int button,
    int action,
    int mods
);

// Обработка клика по игровому полю.
// mouseX и mouseY — координаты клика в мировых координатах.
// Определяет:
//  - по какой клетке кликнули
//  - открыть клетку или поставить флаг
void mouse_click_on_field(double mouseX, double mouseY);

// -----------------------------------------------------
// Camera / Zoom helpers
// -----------------------------------------------------

// Возвращает минимально допустимый зум.
// Нужен, чтобы поле нельзя было "уменьшить в точку".
float get_min_zoom(void);

// Ограничивает смещение камеры.
// Не даёт утащить поле слишком далеко за экран.
void clamp_camera(void);